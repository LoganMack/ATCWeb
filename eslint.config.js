// ESLint flat config. Lint is advisory only: every rule is downgraded to a
// warning (see `warnOnly` below), so `npm run lint` never fails a build or CI.
import js from '@eslint/js';
import astro from 'eslint-plugin-astro';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/** Rewrites every rule severity of "error" to "warn", keeping rule options. */
function warnOnly(config) {
  if (!config.rules) return config;
  const rules = Object.fromEntries(
    Object.entries(config.rules).map(([name, setting]) => {
      if (Array.isArray(setting)) return [name, [toWarn(setting[0]), ...setting.slice(1)]];
      return [name, toWarn(setting)];
    }),
  );
  return { ...config, rules };
}

function toWarn(severity) {
  return severity === 'error' || severity === 2 ? 'warn' : severity;
}

export default [
  {
    ignores: [
      'dist/',
      'node_modules/',
      // Tool folders (build caches, editor and assistant settings) are never linted.
      '.*/',
      'src/scripts/vendor/',
      // Generated by scripts/generate-world-map.mjs.
      'src/lib/worldMap.ts',
      'supabase/',
      'design/',
      'public/',
      // Root-level HTML design mockups, not part of the site.
      '*.html',
    ],
  },
  js.configs.recommended,
  // Without type-aware rules: they need a full type-check per run and are slow.
  ...tseslint.configs.recommended,
  // After typescript-eslint so the Astro parser wins for .astro files.
  ...astro.configs.recommended,
  {
    // Astro frontmatter is TypeScript: `astro check` reports undefined names, and
    // no-undef misreads type-only globals such as FormDataEntryValue.
    files: ['**/*.astro'],
    rules: { 'no-undef': 'off' },
  },
  {
    // Client-side modules bundled for the browser.
    files: ['src/scripts/**'],
    languageOptions: { globals: { ...globals.browser } },
  },
  {
    // Server code runs in the Cloudflare Worker; scripts and configs run in Node.
    files: ['src/lib/**', 'src/middleware.ts', 'scripts/**', '*.config.{js,mjs,cjs,ts}', '*.mjs'],
    languageOptions: { globals: { ...globals.node, ...globals.serviceworker } },
  },
].map(warnOnly);
