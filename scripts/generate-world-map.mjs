// Regenerates src/lib/worldMap.ts — the built-in world outline the Calendar's
// Map view draws (no tile server, no API key, no third-party requests).
//
// Run from a scratch folder so nothing is added to package.json:
//   mkdir /tmp/wm && cd /tmp/wm && npm init -y && npm i world-atlas@2 topojson-client@3
//   node <repo>/scripts/generate-world-map.mjs /tmp/wm <repo>/src/lib/worldMap.ts
//
// Land comes from Natural Earth (public domain) via the world-atlas package,
// projected with the Equal Earth projection (Šavrič, Patterson & Jenny, 2018).
// The same forward projection is baked into the generated file's project(),
// so pins land exactly on the outline.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const [, , dir = '.', out = 'worldMap.ts'] = process.argv;
const require = createRequire(path.resolve(dir) + '/');
const topo = require('world-atlas/land-110m.json');
const { feature } = require('topojson-client');

const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796;
const RAD = Math.PI / 180;
function eq(lng, lat) {
  const th = Math.asin((Math.sqrt(3) / 2) * Math.sin(lat * RAD));
  const t2 = th * th, t6 = t2 * t2 * t2;
  const x = (2 * Math.sqrt(3) * lng * RAD * Math.cos(th)) / (3 * (9 * A4 * t6 * t2 + 7 * A3 * t6 + 3 * A2 * t2 + A1));
  const y = th * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [x, y];
}
const LAT_TOP = 84, LAT_BOTTOM = -58;
const xMax = eq(180, 0)[0];
const yTop = eq(0, LAT_TOP)[1];
const yBot = eq(0, LAT_BOTTOM)[1];
const W = 1000;
const S = W / (2 * xMax);
const H = Math.round((yTop - yBot) * S);
const f = (n) => Math.round(n * 10) / 10;
const proj = (lng, lat) => {
  const [x, y] = eq(lng, lat);
  return [f(W / 2 + x * S), f((yTop - y) * S)];
};

// Sutherland-Hodgman against one meridian: keep the part with lng <= edge (below) or lng >= edge (!below).
function clip(ring, edge, below) {
  const inside = (p) => (below ? p[0] <= edge : p[0] >= edge);
  const out = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i];
    const b = ring[(i + 1) % ring.length];
    if (inside(a)) out.push(a);
    if (inside(a) !== inside(b)) {
      const t = (edge - a[0]) / (b[0] - a[0]);
      out.push([edge, a[1] + t * (b[1] - a[1])]);
    }
  }
  return out;
}

const land = feature(topo, topo.objects.land);
let d = '';
for (const g of land.geometry ? [land.geometry] : land.features.map((x) => x.geometry)) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) {
    const maxLat = Math.max(...poly[0].map((p) => p[1]));
    if (maxLat < LAT_BOTTOM) continue; // Antarctica etc. — below the cropped map
    for (const ring of poly) {
      // Rings that cross the antimeridian jump ~360 degrees between two points;
      // unwrap them into one continuous ring past +/-180, then clip it at the
      // meridian into a west part and an east part so both sides get filled.
      let off = 0;
      let prev = 0;
      const un = ring.map((p, i) => {
        if (i) {
          const jump = p[0] + off - prev;
          if (jump > 180) off -= 360;
          else if (jump < -180) off += 360;
        }
        prev = p[0] + off;
        return [prev, p[1]];
      });
      const lo = Math.min(...un.map((p) => p[0]));
      const hi = Math.max(...un.map((p) => p[0]));
      const parts = [];
      if (hi > 180) {
        parts.push(clip(un, 180, true), clip(un, 180, false).map((p) => [p[0] - 360, p[1]]));
      } else if (lo < -180) {
        parts.push(clip(un, -180, false), clip(un, -180, true).map((p) => [p[0] + 360, p[1]]));
      } else parts.push(un);
      for (const part of parts) {
        if (part.length < 3) continue;
        d += part.map((p, i) => `${i ? 'L' : 'M'}${proj(p[0], p[1]).join(',')}`).join('') + 'Z';
      }
    }
  }
}

const src = `// GENERATED by scripts/generate-world-map.mjs — do not edit by hand.
// Natural Earth land (public domain), Equal Earth projection, ${W}x${H} viewBox.

export const MAP_W = ${W};
export const MAP_H = ${H};

const A1 = ${A1}, A2 = ${A2}, A3 = ${A3}, A4 = ${A4};
const RAD = Math.PI / 180;
const S = ${S};
const Y_TOP = ${yTop};

/** Longitude/latitude in degrees -> map x/y (same space as LAND_PATH). */
export function project(lng: number, lat: number): [number, number] {
  const th = Math.asin((Math.sqrt(3) / 2) * Math.sin(lat * RAD));
  const t2 = th * th;
  const t6 = t2 * t2 * t2;
  const x = (2 * Math.sqrt(3) * lng * RAD * Math.cos(th)) / (3 * (9 * A4 * t6 * t2 + 7 * A3 * t6 + 3 * A2 * t2 + A1));
  const y = th * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [MAP_W / 2 + x * S, (Y_TOP - y) * S];
}

/** Lat/lng grid lines every 30 degrees, as one SVG path. */
export function graticulePath(): string {
  let d = '';
  for (let lng = -180; lng <= 180; lng += 30) {
    for (let lat = ${LAT_BOTTOM}; lat <= ${LAT_TOP}; lat += 2) {
      const [x, y] = project(lng, lat);
      d += \`\${lat === ${LAT_BOTTOM} ? 'M' : 'L'}\${x.toFixed(1)},\${y.toFixed(1)}\`;
    }
  }
  for (let lat = -30; lat <= 60; lat += 30) {
    for (let lng = -180; lng <= 180; lng += 4) {
      const [x, y] = project(lng, lat);
      d += \`\${lng === -180 ? 'M' : 'L'}\${x.toFixed(1)},\${y.toFixed(1)}\`;
    }
  }
  return d;
}

export const LAND_PATH =
  '${d}';
`;
writeFileSync(out, src);
console.log('wrote', out, src.length, 'bytes', W + 'x' + H);
